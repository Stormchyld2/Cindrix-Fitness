package com.cindrix.fitness

data class Timed(val rounds: Int, val workSec: Int, val restSec: Int, val focus: List<String>)

data class Exercise(
    val id: String,
    val name: String,
    val group: String,
    val setup: String,
    val startLb: Int,
    val startNote: String,
    val rx: String,
    val sets: Int,
    val repsLo: Int,
    val repsHi: Int,
    val restSec: Int,
    val cues: List<String>,
    val sub: String,
    val subId: String? = null,
    val inGuide: Boolean = true,
    val timed: Timed? = null,
    val perSide: Boolean = false,
)

private fun s(
    id: String, name: String, group: String, setup: String, startLb: Int, startNote: String,
    rest: Int, cues: List<String>, sub: String, subId: String? = null,
    inGuide: Boolean = true, perSide: Boolean = false, sets: Int = 3, lo: Int = 10, hi: Int = 15,
): Exercise {
    val side = if (perSide) " each side" else ""
    val restText = if (rest >= 60) "60–90 seconds" else "30–45 seconds"
    return Exercise(
        id, name, group, setup, startLb, startNote,
        "$sets sets x $lo–$hi$side; $restText rest between sets",
        sets, lo, hi, rest, cues, sub, subId, inGuide, null, perSide,
    )
}

private fun t(
    id: String, name: String, group: String, setup: String, cues: List<String>, timed: Timed,
    sub: String = "", subId: String? = null,
): Exercise = Exercise(
    id, name, group, setup, 0, "", "${timed.rounds} round(s)", 1, 1, 1, timed.restSec,
    cues, sub, subId, true, timed, false,
)

